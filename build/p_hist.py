def gantt(eps):
    yr0,yr1=44,96; W=1000; rowh=26; Hh=len(eps)*rowh+60
    def X(y): return 140+(y-yr0)/(yr1-yr0)*(W-160)
    import re
    s=f'<svg class="gantt" viewBox="0 0 {W} {Hh}" role="img" aria-label="书信写作年代图">'
    for y in range(45,96,5): s+=f'<line x1="{X(y):.0f}" y1="20" x2="{X(y):.0f}" y2="{Hh-20}" class="gl"/><text x="{X(y):.0f}" y="14" text-anchor="middle" class="gy">{y}</text>'
    for y,lab in ((64,"罗马大火"),(70,"圣殿被毁")): s+=f'<line x1="{X(y):.0f}" y1="20" x2="{X(y):.0f}" y2="{Hh-20}" class="gev"/><text x="{X(y)+4:.0f}" y="{Hh-6}" class="gevt">{lab} {y}</text>'
    for i,e in enumerate(sorted(eps,key=lambda e:int(re.findall(r"(\d+)",e["date"])[0]))):
        ns=[int(x) for x in re.findall(r"(\d{2})",e["date"])[:2]]; a=ns[0]; b=ns[1] if len(ns)>1 and ns[1]>=a else a+1
        y=30+i*rowh; col=GN[e["g"]][1]
        s+=f'<text x="132" y="{y+15}" text-anchor="end" class="gn">{e["n"]}</text><rect x="{X(a):.0f}" y="{y+3}" width="{max(8,X(b)-X(a)):.0f}" height="16" rx="8" fill="{col}" class="gb" style="--d:{i*60}ms"><title>{e["n"]}：{e["date"]}</title></rect>'
    return s+'</svg>'
